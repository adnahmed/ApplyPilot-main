"""Private, bounded, separate PostgreSQL journal. Only the writer creates its schema."""
from __future__ import annotations

from contextlib import contextmanager
import json
import os
from pathlib import Path
import re
from applypilot import postgres
import time
import tempfile

DEFAULTS = {"retention_days": 7, "max_events": 200_000}
BUCKETS = (0.1, 0.5, 1, 5, 15, 60, 300, 1800)
SCHEMA = """
CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at DOUBLE PRECISION NOT NULL, run_id TEXT NOT NULL, process_id TEXT NOT NULL,
 span_id TEXT NOT NULL, parent_span_id TEXT NOT NULL, cycle_id TEXT NOT NULL, task_id TEXT NOT NULL,
 job_id TEXT NOT NULL, stage TEXT NOT NULL, component TEXT NOT NULL, operation TEXT NOT NULL,
 kind TEXT NOT NULL, severity TEXT NOT NULL, outcome TEXT NOT NULL, error_kind TEXT NOT NULL,
 message TEXT NOT NULL, details TEXT NOT NULL, duration DOUBLE PRECISION NOT NULL, fingerprint TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS events_run ON events(run_id, id DESC);
CREATE INDEX IF NOT EXISTS events_at ON events(at);
CREATE INDEX IF NOT EXISTS events_severity ON events(severity, id DESC);
CREATE INDEX IF NOT EXISTS events_run_span_kind ON events(run_id,span_id,kind);
CREATE INDEX IF NOT EXISTS events_run_kind_at ON events(run_id,kind,at);
CREATE INDEX IF NOT EXISTS events_task ON events(task_id,id DESC);
CREATE TABLE IF NOT EXISTS counters (
 stage TEXT, component TEXT, operation TEXT, outcome TEXT, count INTEGER NOT NULL,
 duration DOUBLE PRECISION NOT NULL, buckets TEXT NOT NULL, last_at DOUBLE PRECISION NOT NULL,
 PRIMARY KEY(stage,component,operation,outcome));
CREATE TABLE IF NOT EXISTS incidents (
 fingerprint TEXT PRIMARY KEY, stage TEXT, component TEXT, operation TEXT, error_kind TEXT,
 severity TEXT NOT NULL, message TEXT, details TEXT, first_at DOUBLE PRECISION, last_at DOUBLE PRECISION,
 occurrences INTEGER NOT NULL, last_run_id TEXT, acknowledged_at DOUBLE PRECISION,
 display_severity TEXT);
CREATE TABLE IF NOT EXISTS processes (
 id TEXT PRIMARY KEY, run_id TEXT, pid INTEGER, role TEXT, heartbeat DOUBLE PRECISION,
 dropped INTEGER NOT NULL, write_errors INTEGER NOT NULL, queue_depth INTEGER NOT NULL,
 running INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS runs (
 id TEXT PRIMARY KEY, role TEXT NOT NULL, started_at DOUBLE PRECISION NOT NULL, last_at DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS active (
 span_id TEXT PRIMARY KEY, process_id TEXT, run_id TEXT, stage TEXT, component TEXT,
 operation TEXT, started_at DOUBLE PRECISION);
CREATE INDEX IF NOT EXISTS active_run_process ON active(run_id,process_id);
CREATE INDEX IF NOT EXISTS processes_run_heartbeat ON processes(run_id,heartbeat);
CREATE INDEX IF NOT EXISTS incidents_recent ON incidents(last_at DESC);
CREATE TABLE IF NOT EXISTS gauges (stage TEXT, name TEXT, value DOUBLE PRECISION, updated_at DOUBLE PRECISION, PRIMARY KEY(stage,name));
CREATE TABLE IF NOT EXISTS items (stage TEXT, component TEXT, operation TEXT, measure TEXT, count DOUBLE PRECISION,
 PRIMARY KEY(stage,component,operation,measure));
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS journal_batches (id TEXT PRIMARY KEY, committed_at DOUBLE PRECISION NOT NULL);
"""


def root_path(root=None):
    if root is None:
        from applypilot.config import APP_DIR
        root = APP_DIR
    return Path(root) / "operations"


def settings(root=None):
    try:
        raw = json.loads((root_path(root) / "settings.json").read_text(encoding="utf-8"))
        return validate_settings(raw)
    except (OSError, ValueError, TypeError):
        return dict(DEFAULTS)


def validate_settings(data):
    if not isinstance(data, dict) or set(data) - set(DEFAULTS):
        raise ValueError("Only retention_days and max_events are operational settings")
    result = {**DEFAULTS, **data}
    for key, low, high in (("retention_days", 1, 90), ("max_events", 1000, 2_000_000)):
        if type(result[key]) is not int or not low <= result[key] <= high:
            raise ValueError(f"{key} must be an integer between {low} and {high}")
    return result


def save_settings(root, data):
    value = validate_settings(data)
    folder = root_path(root)
    folder.mkdir(parents=True, exist_ok=True, mode=0o700)
    path = folder / "settings.json"
    fd, name = tempfile.mkstemp(prefix="settings-", suffix=".tmp", dir=folder)
    tmp = Path(name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(value, handle)
        tmp.chmod(0o600)
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)
    return value






def initialize(root=None):
    """Explicit deployment of retained diagnostic history, never called by emit."""
    path = root_path(root) / "events.pgstore"
    postgres.initialize_store(path)
    conn = postgres.connect(path)
    try:
        with conn.schema_lock():
            conn.executescript(SCHEMA)
        conn.commit()
    finally:
        conn.close()


def connect_writer(root=None):
    conn = postgres.connect(root_path(root) / "events.pgstore", timeout=5)
    conn.row_factory = postgres.Row
    return conn


@contextmanager
def reader(root=None):
    path = root_path(root) / "events.pgstore"
    from applypilot.postgres_reads import connect_readonly
    conn = connect_readonly(path, timeout=1.5)
    try:
        yield conn
    finally:
        try:
            conn.rollback()
        finally:
            conn.close()


def append(conn, batch, *, batch_id=None):
    """Event insertion and aggregate updates are one short transaction."""
    runs = {}
    with conn:
        conn.advisory_lock("operations-append")
        if batch_id is not None:
            if not re.fullmatch(r"[0-9a-f]{32}", batch_id):
                raise ValueError("Invalid journal batch identity")
            if not conn.execute('INSERT INTO journal_batches VALUES(?,?) ON CONFLICT DO NOTHING', (batch_id, time.time())).rowcount:
                return  # The entire batch and its aggregates already committed.
        for event in batch:
            if event.get("outcome") == "needs_human":
                # A journal batch written by an older process may be replayed.
                event = {**event, "outcome": "failed"}
            fields = ("at", "run_id", "process_id", "span_id", "parent_span_id", "cycle_id", "task_id",
                      "job_id", "stage", "component", "operation", "kind", "severity", "outcome", "error_kind",
                      "message", "details", "duration", "fingerprint")
            conn.execute("INSERT INTO events(" + ",".join(fields) + ") VALUES(" +
                         ",".join("?" for _ in fields) + ")", tuple(event[field] for field in fields))
            run = runs.setdefault(event["run_id"], [event.get("role", "worker"), event["at"], event["at"]])
            run[2] = event["at"]
            details = json.loads(event["details"])
            if event["kind"] == "gauge" and type(details.get("pending")) in {int, float}:
                conn.execute('INSERT INTO gauges VALUES(?,?,?,?) ON CONFLICT (stage,name) DO UPDATE SET name=excluded.name, value=excluded.value, updated_at=excluded.updated_at', (event["stage"], "pending", details["pending"], event["at"]))
            if event["kind"] == "finish":
                for measure in ("found", "new", "existing", "selected", "scored", "sent", "pages"):
                    if type(details.get(measure)) in {int, float}:
                        conn.execute("INSERT INTO items VALUES(?,?,?,?,?) ON CONFLICT(stage,component,operation,measure) "
                            "DO UPDATE SET count=items.count+excluded.count", (event["stage"], event["component"], event["operation"], measure, details[measure]))
            if event["kind"] == "start":
                conn.execute('INSERT INTO active VALUES(?,?,?,?,?,?,?) ON CONFLICT (span_id) DO UPDATE SET process_id=excluded.process_id, run_id=excluded.run_id, stage=excluded.stage, component=excluded.component, operation=excluded.operation, started_at=excluded.started_at', (
                    event["span_id"], event["process_id"], event["run_id"], event["stage"],
                    event["component"], event["operation"], event["at"]))
            if event["kind"] == "finish":
                conn.execute("DELETE FROM active WHERE span_id=?", (event["span_id"],))
                key = tuple(event[k] for k in ("stage", "component", "operation", "outcome"))
                row = conn.execute("SELECT buckets FROM counters WHERE stage=? AND component=? AND operation=? AND outcome=?", key).fetchone()
                counts = json.loads(row[0]) if row else [0] * len(BUCKETS)
                counts = [v + int(event["duration"] <= b) for b, v in zip(BUCKETS, counts)]
                conn.execute("INSERT INTO counters VALUES(?,?,?,?,1,?,?,?) ON CONFLICT(stage,component,operation,outcome) "
                    "DO UPDATE SET count=counters.count+1,duration=counters.duration+excluded.duration,buckets=excluded.buckets,last_at=excluded.last_at",
                    (*key, event["duration"], json.dumps(counts), event["at"]))
            if event["severity"] in {"warning", "error", "critical"}:
                conn.execute("INSERT INTO incidents VALUES(?,?,?,?,?,?,?,?,?,?,1,?,NULL,NULL) "
                    "ON CONFLICT(fingerprint) DO UPDATE SET last_at=excluded.last_at,occurrences=incidents.occurrences+1,"
                    "message=excluded.message,details=excluded.details,last_run_id=excluded.last_run_id,"
                    "severity=CASE WHEN excluded.severity='critical' THEN 'critical' WHEN excluded.severity='error' "
                    "AND incidents.severity!='critical' THEN 'error' ELSE incidents.severity END", (
                        event["fingerprint"], event["stage"], event["component"], event["operation"],
                        event["error_kind"], event["severity"], event["message"], event["details"],
                        event["at"], event["at"], event["run_id"]))
        for run_id, values in runs.items():
            conn.execute("INSERT INTO runs VALUES(?,?,?,?) ON CONFLICT(id) DO UPDATE SET last_at=excluded.last_at",
                         (run_id, *values))


def prune(conn, root=None):
    cfg = settings(root)
    now = time.time()
    def recently_pruned():
        row = conn.execute("SELECT value FROM meta WHERE key='last_prune'").fetchone()
        return row is not None and 0 <= time.time() - float(row[0]) < 60
    # All journal processes share this retention pass. Do not have every model
    # and browser helper compete to prune the same database on startup.
    if conn.in_transaction or recently_pruned():
        return
    cutoff = now - cfg["retention_days"] * 86400
    with conn:
        conn.advisory_lock("operations-prune")
        if recently_pruned():
            return
        conn.execute("DELETE FROM events WHERE at<?", (cutoff,))
        row = conn.execute("SELECT id FROM events ORDER BY id DESC LIMIT 1 OFFSET ?", (cfg["max_events"] - 1,)).fetchone()
        if row:
            conn.execute("DELETE FROM events WHERE id<?", (row[0],))
        conn.execute("DELETE FROM incidents WHERE last_at<?", (cutoff,))
        conn.execute("DELETE FROM incidents WHERE fingerprint IN (SELECT fingerprint FROM incidents ORDER BY last_at DESC OFFSET 10000)")
        conn.execute("DELETE FROM active WHERE process_id IN (SELECT id FROM processes WHERE running=0 OR heartbeat<?)", (time.time() - 120,))
        conn.execute("DELETE FROM processes WHERE heartbeat<?", (cutoff,))
        conn.execute("DELETE FROM runs WHERE last_at<?", (cutoff,))
        conn.execute("DELETE FROM journal_batches WHERE committed_at<?", (cutoff,))
        conn.execute("INSERT INTO meta VALUES('last_prune',?) ON CONFLICT (key) DO UPDATE SET value=excluded.value", (str(time.time()),))


def number(value, default, low, high):
    try:
        return min(high, max(low, int(value)))
    except (ValueError, TypeError):
        return default


def event_query(q):
    clauses, params = [], []
    if q.get("view") == "significant":
        # Apply this before LIMIT/pagination, not to an already full page of
        # backup checks. Preserve every warning/error and every audit row.
        clauses.append("(severity IN ('warning','error','critical') OR "
            "(kind NOT IN ('start','gauge') AND NOT (stage='backup' "
            "AND component='backup' AND operation='sync' AND severity='info' "
            "AND ((outcome='deferred' AND message='backoff') "
            "OR (outcome='skipped' AND message='not_due')))))")
    for key in ("run_id", "cycle_id", "task_id", "job_id", "stage", "component", "severity", "outcome"):
        if q.get(key):
            if key == "severity" and q[key] == "error" and q.get("include_critical") is True:
                clauses.append("severity IN ('error','critical')")
                continue
            clauses.append(f"{key}=?")
            params.append(str(q[key])[:160])
    if q.get("source"):
        # SDK events retain the real source in integration metadata. Match it
        # before LIMIT so selecting a source cannot hide its older failures.
        clauses.append("COALESCE(NULLIF(CASE WHEN ap_json_valid(details) THEN "
                       "ap_json_text(details,'$.integration') END,''),component)=?")
        params.append(str(q["source"])[:160])
    if q.get("before"):
        clauses.append("id<?")
        params.append(number(q["before"], 0, 0, 2**63 - 1))
    for term in str(q.get("q") or "")[:200].split():
        fields = ("message", "error_kind", "component", "operation", "stage", "severity",
                  "outcome", "run_id", "span_id", "task_id", "job_id", "details", "id")
        clauses.append("(" + " OR ".join(f"strpos(lower(COALESCE(CAST({field} AS TEXT),'')),lower(?))>0"
                                         for field in fields) + ")")
        params.extend([term] * len(fields))
    return (" WHERE " + " AND ".join(clauses) if clauses else ""), params


def decoded_details(value):
    """A malformed historical detail row must not take the Operations UI down."""
    try:
        result = json.loads(value)
        return result if isinstance(result, dict) else {"details_decode_error": "Expected an object"}
    except (ValueError, TypeError):
        return {"details_decode_error": "Stored detail JSON is unreadable; original record retained"}


def events(root, q):
    where, params = event_query(q)
    limit = number(q.get("limit"), 100, 1, 1000)
    with reader(root) as conn:
        rows = [dict(r) for r in conn.execute("SELECT * FROM events" + where + " ORDER BY id DESC LIMIT ?", (*params, limit + 1))]
    more = len(rows) > limit
    rows = rows[:limit]
    for row in rows:
        row["details"] = decoded_details(row["details"])
    filter_keys = ("run_id", "cycle_id", "task_id", "job_id", "stage", "component", "source",
                   "severity", "outcome", "before", "q")
    return {"items": rows, "next_before": rows[-1]["id"] if more else None,
            "scope": {"kind": "filtered_event_page", "generated_at": time.time(),
                      "view": "significant" if q.get("view") == "significant" else "all",
                      "filters": {key: str(q[key])[:200] for key in filter_keys if q.get(key)},
                      "limit": limit, "returned": len(rows), "has_more": more,
                      "oldest_at": min((r["at"] for r in rows), default=None),
                      "newest_at": max((r["at"] for r in rows), default=None)}}


def overview(root):
    value = {"available": False, "settings": settings(root), "runs": [], "processes": [], "incidents": [],
             "counters": [], "gauges": [], "active": [], "events": {"items": [], "next_before": None}, "error": None}
    try:
        with reader(root) as conn:
            value["runs"] = [dict(r) for r in conn.execute("SELECT * FROM runs ORDER BY last_at DESC LIMIT 100")]
            value["processes"] = [dict(r) for r in conn.execute("SELECT * FROM processes ORDER BY heartbeat DESC LIMIT 200")]
            value["incidents"] = [dict(r) for r in conn.execute("SELECT * FROM incidents ORDER BY (acknowledged_at IS NULL OR last_at>acknowledged_at) DESC,last_at DESC LIMIT 100")]
            value["gauges"] = [dict(r) for r in conn.execute("SELECT * FROM gauges")]
            value["counters"] = [dict(r) for r in conn.execute("SELECT * FROM counters ORDER BY stage,component,operation,outcome")]
            value["active"] = [dict(r) for r in conn.execute("SELECT a.* FROM active a JOIN processes p ON p.id=a.process_id WHERE p.running=1 AND p.heartbeat>? ORDER BY started_at LIMIT 1000", (time.time() - 120,))]
            value["unacknowledged"] = conn.execute("SELECT COUNT(*) FROM incidents WHERE acknowledged_at IS NULL OR last_at>acknowledged_at").fetchone()[0]
            value["event_count"] = conn.execute("SELECT COUNT(*) FROM events").fetchone()[0]
        value["available"] = True
        for item in value["incidents"]:
            item["details"] = decoded_details(item["details"])
        for process in value["processes"]:
            process["state"] = ("stopped" if not process["running"] else "stale" if time.time() - process["heartbeat"] > 120 else "alive")
    except (postgres.Error, OSError, ValueError):
        value["available"] = False
        value["error"] = "No readable operations journal yet. Start the application engine; metrics never imply health when data is missing."
    return value


def incident_action(root, data):
    """Atomic presentation-only actions, including reversal of review state.

    Snapshot timestamps ensure that acknowledging a displayed row cannot hide a
    later occurrence. Bulk actions have the same safeguards as single actions.
    """
    if set(data) - {"fingerprint", "action", "last_at", "items"}:
        raise ValueError("Unexpected incident fields")
    action = data.get("action")
    if action not in {"acknowledge", "unacknowledge", "warning", "reset"}:
        raise ValueError("Select review, undo review, warning or reset")
    items = data.get("items")
    if items is None:
        items = [{"fingerprint": data.get("fingerprint"), "last_at": data.get("last_at")}]
    elif "fingerprint" in data or "last_at" in data:
        raise ValueError("Choose a single incident or a selection, not both")
    if not isinstance(items, list) or not 1 <= len(items) <= 100:
        raise ValueError("Select between 1 and 100 incident groups")
    seen = set()
    for item in items:
        if not isinstance(item, dict) or set(item) - {"fingerprint", "last_at"}:
            raise ValueError("Invalid incident selection")
        fp = item.get("fingerprint")
        if not isinstance(fp, str) or not re.fullmatch(r"[a-f0-9]{32}", fp) or fp in seen:
            raise ValueError("Select distinct recorded incident groups")
        seen.add(fp)
        if action == "acknowledge":
            at = item.get("last_at")
            if type(at) not in {float, int} or not 0 < at <= time.time() + 1:
                raise ValueError("Reload the selection before marking it reviewed")
    conn = connect_writer(root)
    try:
        with conn:
            for item in items:
                fp = item["fingerprint"]
                row = conn.execute("SELECT error_kind,severity FROM incidents WHERE fingerprint=?", (fp,)).fetchone()
                if row is None:
                    raise ValueError("An incident is no longer retained. Reload your selection.")
                if action == "warning" and (row[0] in {"storage", "send_unknown", "security"} or row[1] == "critical"):
                    raise ValueError("Storage, uncertain-send, security and critical incidents cannot be demoted")
                if action == "acknowledge":
                    conn.execute("UPDATE incidents SET acknowledged_at=GREATEST(COALESCE(acknowledged_at,0),LEAST(last_at,?)) WHERE fingerprint=?", (item["last_at"], fp))
                elif action == "unacknowledge":
                    conn.execute("UPDATE incidents SET acknowledged_at=NULL WHERE fingerprint=?", (fp,))
                else:
                    conn.execute("UPDATE incidents SET display_severity=? WHERE fingerprint=?", ("warning" if action == "warning" else None, fp))
        return {"ok": True, "updated": len(items)}
    finally:
        conn.close()


def summary(root):
    value = {"available": False, "unacknowledged": 0, "stale": 0, "dropped": 0, "write_errors": 0}
    try:
        with reader(root) as conn:
            value["unacknowledged"] = conn.execute("SELECT COUNT(*) FROM incidents WHERE acknowledged_at IS NULL OR last_at>acknowledged_at").fetchone()[0]
            value["stale"] = conn.execute("SELECT COUNT(*) FROM processes WHERE running=1 AND heartbeat<?", (time.time() - 120,)).fetchone()[0]
            row = conn.execute("SELECT COALESCE(SUM(dropped),0),COALESCE(SUM(write_errors),0) FROM processes").fetchone()
            value.update(available=True, dropped=row[0], write_errors=row[1])
    except (postgres.Error, OSError):
        pass
    return value
