def dumps(value) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False, default=str)


def root() -> Path:
    from applypilot import config
    return Path(os.getenv("APPLYPILOT_LEARNING_DIR", str(config.APP_DIR / "learning"))).expanduser().resolve()


def initialize(directory: Path | None = None):
    """Deploy the learning corpus before starting workers; no model execution."""
    directory = Path(directory) if directory is not None else root()
    path = directory / "learning.pgstore"
    if path.is_symlink():
        raise OSError("Redirected learning database")
    postgres.initialize_store(path)
    connection = postgres.connect(path)
    try:
        with connection.schema_lock():
            connection.executescript(SCHEMA)
            if connection.execute("SELECT 1 FROM pg_tables WHERE schemaname=current_schema() AND tablename='locks'").fetchone():
                connection.execute("CREATE TABLE IF NOT EXISTS retired_execution_locks (LIKE locks INCLUDING ALL)")
                connection.execute("INSERT INTO retired_execution_locks SELECT * FROM locks ON CONFLICT DO NOTHING")
                connection.execute("DROP TABLE locks")
            if connection.execute(
                "SELECT 1 FROM pg_constraint WHERE conrelid='examples'::regclass "
                "AND conname='examples_task_schema_hash_messages_key' AND contype='u'"
            ).fetchone():
                connection.execute("ALTER TABLE examples DROP CONSTRAINT examples_task_schema_hash_messages_key")
        connection.commit()
    finally:
        connection.close()


@contextmanager
def database(directory: Path | None = None):
    directory = Path(directory) if directory is not None else root()
    path = directory / "learning.pgstore"
    if path.is_symlink():
        raise OSError("Redirected learning database")
    connection = postgres.connect(path, timeout=3)
    try:
        connection.row_factory = postgres.Row
        with connection:
            yield connection
    finally:
        connection.close()


def mode_defaults() -> dict:
    """Full is unattended optimization AND judged promotion, not verified success.

    Environment values are defaults. Explicit saved owner choices still win;
    `learning defaults` clears those overrides without deleting learned policies.
    """
    mode = os.getenv("APPLYPILOT_LEARNING_MODE", "full").strip().lower()
    if mode not in {"full", "optimize", "capture"}:
        raise ValueError("APPLYPILOT_LEARNING_MODE must be full, optimize, or capture")
    return {"enabled": flag("APPLYPILOT_LEARNING_ENABLED", mode != "capture"),
            "auto_promote": flag("APPLYPILOT_LEARNING_AUTO_PROMOTE", mode == "full"),
            "allow_judged_promotion": flag("APPLYPILOT_LEARNING_ALLOW_JUDGED_PROMOTION", mode == "full")}


def settings() -> dict:
    defaults = {**mode_defaults(),
                "min_examples": integer("APPLYPILOT_LEARNING_MIN_EXAMPLES", 30, 6),
                "metric_calls": integer("APPLYPILOT_LEARNING_METRIC_CALLS", 40, 1),
                "mipro_candidates": integer("APPLYPILOT_LEARNING_MIPRO_CANDIDATES", 4, 2),
                "mipro_trials": integer("APPLYPILOT_LEARNING_MIPRO_TRIALS", 10, 1),
                "min_improvement": 0.05}
    path = root() / "settings.json"
    if path.exists():
        saved = json.loads(path.read_text(encoding="utf-8"))
        retired = {"max_calls", "max_output_tokens", "timeout", "cooldown", "retry_seconds"}
        for key, value in saved.items():
            if key in retired:
                continue
            if key not in defaults or type(value) is not type(defaults[key]):
                raise ValueError("Invalid learning setting " + str(key))
            if type(value) in (int, float) and (
                    not math.isfinite(value) or value < 0 or (value == 0 and key != "timeout")):
                raise ValueError("Learning numeric settings must be positive; timeout=0 disables its limit")
            defaults[key] = value
    if defaults["min_examples"] < 6 or not 0 < defaults["min_improvement"] <= 1:
        raise ValueError("Learning requires disjoint groups and positive improvement")
    return defaults


def save_settings(changes: dict) -> dict:
    from applypilot import config
    from applypilot.onboarding.storage import setup_lock
    with setup_lock(config.APP_DIR):
        return _save_settings(changes)


def _save_settings(changes: dict) -> dict:
    from .source_files import SourceFiles
    prior = settings()
    value = prior | changes
    directory = root()
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    path = directory / "settings.json"
    # Validate types before persisting; numeric bounds checked by settings().
    for key, item in changes.items():
        if key not in prior or type(item) is not type(prior[key]):
            raise ValueError("Invalid learning setting")
    if any(type(v) in (int, float) and (not math.isfinite(v) or v < 0 or (v == 0 and k != "timeout"))
           for k, v in value.items()):
        raise ValueError("Numeric settings must be positive; timeout=0 disables its limit")
    if value["min_examples"] < 6 or not 0 < value["min_improvement"] <= 1:
        raise ValueError("Invalid minimum examples/improvement")
    # Save only owner overrides: do not freeze unrelated environment defaults.
    saved = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    SourceFiles._write(path, dumps(saved | changes))
    path.chmod(0o700)
    return settings()


def configure_mode(data: dict) -> dict:
    if set(data) != {"mode", "confirm"} or data["confirm"] is not True:
        raise ValueError("Confirm the learning-mode change")
    mode = data["mode"]
    if mode == "full":
        return save_settings({"enabled": True, "auto_promote": True, "allow_judged_promotion": True})
    if mode == "optimize":
        return save_settings({"enabled": True, "auto_promote": False, "allow_judged_promotion": False})
    if mode == "capture":
        return save_settings({"enabled": False, "auto_promote": False})
    if mode == "defaults":
        from applypilot import config
        from applypilot.onboarding.storage import setup_lock
        mode_defaults()  # Validate the selected mode before discarding overrides.
        with setup_lock(config.APP_DIR):
            (root() / "settings.json").unlink(missing_ok=True)
        return settings()
    raise ValueError("Choose full, optimize, capture or defaults")


